"""Real service probe; only use with a dedicated audit Compose project.
Start stack yourself, then: python3 scripts/verify_storage_compose.py --project rider1808audit --port 18077
The script restarts ONLY that project's app; it does not remove containers or volumes.
"""
import argparse
import json
import subprocess
import time
import urllib.request
import urllib.error

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--project",required=True,choices=["rider1808audit"])
    p.add_argument("--port",required=True,type=int)
    a=p.parse_args()
    base=f"http://127.0.0.1:{a.port}"
    compose=["docker","compose","-p",a.project]
    def run(*args):
        return subprocess.check_output(compose+list(args),text=True,timeout=60).strip()
    def request(path,method="GET",data=None,token=None):
        headers={"Content-Type":"application/json"}
        if token: headers["X-Session-Token"]=token
        req=urllib.request.Request(base+path,method=method,
            data=json.dumps(data).encode() if data is not None else None,headers=headers)
        try:
            with urllib.request.urlopen(req,timeout=15) as r:
                return r.status,json.load(r)
        except urllib.error.HTTPError as e:
            return e.code,json.load(e)
    def healthy():
        for _ in range(30):
            try:
                code,health=request("/healthz")
                if code==200 and health.get("database")=="postgresql" and health.get("pgvector") is True and health.get("redis") is True:
                    return
            except (OSError,ValueError): pass
            time.sleep(2)
        raise AssertionError("Required Postgres/pgvector/Redis health not confirmed")
    # Verify the port belongs to the explicitly isolated app before making requests.
    bound=run("port","app","8077")
    assert bound.endswith(":"+str(a.port)),bound
    healthy()
    code,body=request("/api/v1/agent/sessions","POST",{})
    assert code==201
    sid,token=body["session_id"],body["session_token"]
    path="/api/v1/agent/sessions/"+sid
    for text in ["我叫小王","1995年3月"]:
        code,body=request(path+"/messages","POST",{"text":text},token)
        assert code==200
    assert body["progress"]["done"]==2
    # UUID generated by service; validate before interpolating into read-only SQL.
    import uuid
    sid=str(uuid.UUID(sid))
    db=run("exec","-T","postgres","psql","-U","rider","-d","rider","-At","-c",
           "SELECT payload::text FROM agent_sessions WHERE id='"+sid+"'::uuid;")
    row=json.loads(db)
    assert row["candidate"]["birth_ym"]=="1995-03"
    assert "turns" not in row and token not in db
    assert run("exec","-T","postgres","psql","-U","rider","-d","rider","-At","-c",
               "SELECT count(*) FROM agent_policy_doc WHERE vector_dims(embedding)=256;").isdigit()
    assert int(run("exec","-T","postgres","psql","-U","rider","-d","rider","-At","-c",
                   "SELECT count(*) FROM agent_policy_doc WHERE vector_dims(embedding)=256;"))>0
    code,answer=request("/api/v1/agent/policy/answer?q=%E4%BF%9D%E9%9A%9C%E8%A1%A5%E8%B4%B4&city=BJ")
    assert code==200 and answer.get("found") and answer.get("citation"),answer
    keys=run("exec","-T","redis","redis-cli","--scan","--pattern","agent:policy:v1:*")
    assert keys,"No policy cache entries in Redis"
    run("restart","app")
    healthy()
    code,body=request(path+"/messages","POST",{"text":"住在望京小区"})
    assert code==401
    code,body=request(path+"/messages","POST",{"text":"住在望京小区"},token)
    assert code==200 and body["progress"]["done"]==3,body
    print("PASS: live PostgreSQL row, pgvector rows, Redis cache and app restart continuation")
if __name__=="__main__":
    main()
